def show_recs(mtype):
    if mtype not in recommendations:
        st.info("왼쪽 박스에서 MBTI 유형을 먼저 골라주세요 🙂")
        return
    st.markdown("### ✨ 추천 진로")
    for idx, (job, dept, personality, emoji) in enumerate(recommendations[mtype], start=1):
        st.markdown(f"**{idx}. {job} {emoji}**")
        with st.expander("자세히 보기"):
            st.markdown(f"- **추천 학과(전공)**: {dept}")
            st.markdown(f"- **어떤 성격이 잘 맞을까?**: {personality}")
            # 간단 팁
            if "요리" in job or "파티시에" in job or "디자이너" in job:
                st.markdown("- 🎯 **꿀팁:** 실습·포트폴리오가 중요해요 — 직접 만들어보고 기록해보세요!")
            elif "연구" in job or "데이터" in job or "학자" in job:
                st.markdown("- 🎯 **꿀팁:** 작은 프로젝트로 경험을 쌓고, 논리적으로 정리하는 연습을 해보세요.")
            else:
                st.markdown("- 🎯 **꿀팁:** 체험활동(인턴·동아리·공모전)으로 적성 확인해보는 걸 추천해요.")
        st.write("---")

